-- ---------------------------------------------------------------------------
-- 0004_change_payload —— 为变更记录补上后端私有的回滚数据
--
-- # 为什么需要它
--
-- 0003 建表时只存了渲染后的人类可读差异，没有存后端重建撤销动作所需的
-- 原始数据。当时的结论是"跨进程撤销做不了，让用户手动清理"，
-- 而那个结论是错的 —— 它把框架的一个设计缺口转嫁给了用户。
--
-- 撤销一条防火墙规则必须知道"当初创建了哪几条"。规则名可以从计划推导，
-- 但后端的私有句柄（例如规则的系统内部 Name 与 DisplayName 的对应）
-- 推导不出来。因此必须让后端把需要的东西序列化下来。
--
-- 本列对 change 包完全透明：它原样存、原样交给后端的 Reverter。
-- ---------------------------------------------------------------------------

ALTER TABLE change_journal ADD COLUMN payload BLOB;
